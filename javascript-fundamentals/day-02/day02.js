console.log("Day 02 — Operators and Expressions");

// Arithmetic Operators

const totalTests = 20;
const failedTests = 3;

console.log("Total Tests:", totalTests);
console.log("Failed Tests:", failedTests);
console.log("Passed Tests:", totalTests - failedTests);

console.log("Testers:", 3);
console.log("Tests Per Tester:", 10);
console.log("Total Assigned Tests:", 3 * 10);

console.log("Division Example:", 30 / 3);
console.log("Remainder Example:", 10 % 3);

const totalTestCases = 50;
const passedTestCases = 42;

console.log("Failed Test Cases:", totalTestCases - passedTestCases);
console.log("Test Cases Per Group:", totalTestCases / 5);
console.log("Double Passed Tests:", passedTestCases * 2);
console.log("Remainder:", totalTestCases % 6);

// Comparison Operators

const totalTests = 50;
const passedTests = 42;

console.log("Is totalTests greater than passedTests:", totalTests > passedTests);
console.log("Is passedTests less than totalTests:", passedTests < totalTests);
console.log("Is passedTests greater than 50:", passedTests > 50);
